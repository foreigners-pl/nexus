// Same destinations as the main app so mobile users can jump into the full tool
const navItems = [
  { href: '/mobile', label: 'Home', icon: 'home' as keyof typeof icons, match: '/mobile' },
  { href: '/clients', label: 'Clients', icon: 'clients' as keyof typeof icons, match: '/clients' },
  { href: '/board', label: 'Board', icon: 'board' as keyof typeof icons, match: '/board' },
  { href: '/wiki', label: 'Wiki', icon: 'wiki' as keyof typeof icons, match: '/wiki' },
  { href: '/chat', label: 'Chat', icon: 'chat' as keyof typeof icons, match: '/chat' },
]

export function MobileTabBar() {
  const pathname = usePathname()

  return (
    <nav className="fixed bottom-0 left-0 right-0 bg-[hsl(var(--color-surface))] border-t border-[hsl(var(--color-border))] z-50 safe-area-bottom">
      <div className="flex items-center justify-around h-16 max-w-lg mx-auto">
        {navItems.map((item) => {
          const isActive = item.match === '/mobile'
            ? pathname === '/mobile'
            : pathname.startsWith(item.match)

          return (
            <Link
              key={item.href}
              href={item.href}
              className={cn(
                'flex flex-col items-center justify-center px-3 py-2 min-w-[64px]',
                'text-xs font-medium transition-colors',
                isActive
                  ? 'text-[hsl(var(--color-primary))]'
                  : 'text-[hsl(var(--color-text-secondary))]'
              )}
            >
              {icons[item.icon]}
              <span className="mt-1">{item.label}</span>
            </Link>
          )
        })}
      </div>
    </nav>
  )
}
